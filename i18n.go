func translate(lang Language, key string, args ...any) string {
	lang = normalizeLanguage(lang)
	text := translations[lang][key]
	if text == "" {
		text = translations[LanguageEnglish][key]
	}
	if text == "" {
		text = key
	}
	if len(args) > 0 {
		return fmt.Sprintf(text, args...)
	}
	return text
}
